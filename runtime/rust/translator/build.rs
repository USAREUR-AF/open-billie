//! Embeds the goat-transformers files that tools/sync_goat_transformers_packs.py
//! copied into goat-transformers/: every model module and pack that its
//! SHA256SUMS lists, the models ordered so that each comes after the modules it
//! uses. A module that the copy lacks, but that an embedded pack or module
//! uses, stops the build. The list is read from the copy, not written here, so
//! a pack that begins to use a new module needs only a new sync.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn uses(text: &str) -> Vec<String> {
    text.lines()
        .filter_map(|line| {
            let mut words = line.split_whitespace();
            (words.next() == Some("uses"))
                .then(|| words.next().map(str::to_owned))
                .flatten()
        })
        .collect()
}

fn module_name(relative: &str) -> &str {
    relative
        .trim_start_matches("model/")
        .trim_end_matches(".def")
}

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("goat-transformers");
    let sums = root.join("SHA256SUMS");
    println!("cargo:rerun-if-changed={}", sums.display());
    let listed: Vec<String> = fs::read_to_string(&sums)
        .unwrap_or_else(|e| panic!("{}: {e}", sums.display()))
        .lines()
        .filter_map(|line| line.split_once("  ").map(|(_, name)| name.to_owned()))
        .collect();
    let read = |relative: &str| -> String {
        let path = root.join(relative);
        println!("cargo:rerun-if-changed={}", path.display());
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
    };

    let models: BTreeMap<String, Vec<String>> = listed
        .iter()
        .filter(|name| name.starts_with("model/") && name.ends_with(".def"))
        .map(|name| (module_name(name).to_owned(), uses(&read(name))))
        .collect();
    let packs: Vec<&String> = listed
        .iter()
        .filter(|name| name.starts_with("packs/") && name.ends_with("/pack.def"))
        .collect();

    let mut missing = Vec::new();
    if !models.contains_key("core") {
        missing.push("model/core.def is not copied, and every pack uses core".to_owned());
    }
    let pack_uses: Vec<(String, Vec<String>)> = packs
        .iter()
        .map(|p| ((*p).clone(), uses(&read(p))))
        .collect();
    let module_uses = models
        .iter()
        .map(|(m, u)| (format!("model/{m}.def"), u.clone()));
    for (file, used) in pack_uses.iter().cloned().chain(module_uses) {
        for m in used {
            if !models.contains_key(&m) {
                missing.push(format!("{file} uses {m}, and model/{m}.def is not copied"));
            }
        }
    }
    if !missing.is_empty() {
        panic!(
            "goat-transformers/: {}. Run python3 tools/sync_goat_transformers_packs.py.",
            missing.join("; ")
        );
    }

    // Each module after the modules it uses, core first; ties in name order.
    let mut order: Vec<String> = Vec::new();
    fn visit(
        m: &str,
        models: &BTreeMap<String, Vec<String>>,
        order: &mut Vec<String>,
        path: &mut Vec<String>,
    ) {
        if order.iter().any(|o| o == m) {
            return;
        }
        if path.iter().any(|p| p == m) {
            panic!(
                "goat-transformers/: the model modules use each other in a cycle: {} -> {m}",
                path.join(" -> ")
            );
        }
        path.push(m.to_owned());
        for u in &models[m] {
            visit(u, models, order, path);
        }
        path.pop();
        order.push(m.to_owned());
    }
    visit("core", &models, &mut order, &mut Vec::new());
    for m in models.keys() {
        visit(m, &models, &mut order, &mut Vec::new());
    }

    let entry = |relative: &str| -> String {
        let path: &Path = &root.join(relative);
        format!(
            "    ({relative:?}, include_str!({:?})),\n",
            path.display().to_string()
        )
    };
    let mut out = String::from(
        "/// Model modules, each after the modules it uses (generated by build.rs).\n",
    );
    out += &format!("const MODEL: [(&str, &str); {}] = [\n", order.len());
    for m in &order {
        out += &entry(&format!("model/{m}.def"));
    }
    out += "];\n\n/// The packs, in the order of SHA256SUMS (generated by build.rs).\n";
    out += &format!("const PACKS: [(&str, &str); {}] = [\n", packs.len());
    for p in &packs {
        out += &entry(p);
    }
    out += "];\n";
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("goat_transformers_embedded.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}
